export const giftPathForLanguage = (language) =>
  GIFT_ROUTES[language]?.path || GIFT_ROUTES.IT.path;

export const giftLanguageForPath = (pathname) => {
  const normalizedPath = pathname === '/' ? pathname : pathname.replace(/\/+$/, '');
  return Object.entries(GIFT_ROUTES).find(([, route]) => route.path === normalizedPath)?.[0] || null;
};
